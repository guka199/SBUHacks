-- Run manually in a Snowsight worksheet as the account administrator.
-- This provisions only the PostPilot namespace and its application role.
-- Replace MYKHAILOF if using a different Snowflake user.
USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS POSTPILOT;
CREATE SCHEMA IF NOT EXISTS POSTPILOT.PUBLIC;
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
CREATE ROLE IF NOT EXISTS POSTPILOT_APP;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE POSTPILOT_APP;
GRANT USAGE ON DATABASE POSTPILOT TO ROLE POSTPILOT_APP;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE VIEW
    ON SCHEMA POSTPILOT.PUBLIC TO ROLE POSTPILOT_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA POSTPILOT.PUBLIC
    TO ROLE POSTPILOT_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA POSTPILOT.PUBLIC
    TO ROLE POSTPILOT_APP;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE POSTPILOT_APP;
GRANT USE AI FUNCTIONS ON ACCOUNT TO ROLE POSTPILOT_APP;
GRANT ROLE POSTPILOT_APP TO USER "MYKHAILOF";

-- Then generate a new programmatic access token in Snowsight with its
-- role restriction set to POSTPILOT_APP. Keep the secret in .env only.
-- Set SNOWFLAKE_ROLE=POSTPILOT_APP and restart the API after replacing the token.
